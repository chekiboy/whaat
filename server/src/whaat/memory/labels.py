def label(lang: Language, key: str, fallback: str | None = None, **values: object) -> str:
    """The word for a key in a language; the fallback (or the key) when the dictionary does not know it."""
    text = LABELS[lang].get(key)
    if text is None:
        return fallback if fallback is not None else key
    return text.format(**values) if values else text
